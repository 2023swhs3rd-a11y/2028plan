def R(label, areas, tam, n, kind, val, req='', hist='', eng='', etc=''):
    return dict(label=label, areas=[a for a in areas.split(',') if a], tam=tam, n=n, kind=kind,
                val=val, req=req, hist=hist, eng=eng, etc=etc)


