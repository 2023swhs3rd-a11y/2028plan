def H(rules, h='응시 필수'):
    """전형 전체에 붙는 한국사 조건을 미적용이 아닌 규칙에 붙인다."""
    for x in rules:
        if x['kind'] != '미적용' and not x['hist']:
            x['hist'] = h
    return rules


def E(rules, etc):
    for x in rules:
        if x['kind'] != '미적용':
            x['etc'] = '; '.join(filter(None, [x['etc'], etc]))
    return rules


